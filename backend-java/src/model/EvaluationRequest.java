package model;

public class EvaluationRequest {

    private String name;
    private String question;
    private String modelAnswer;
    private String answer;

    public String getName() {
        return name;
    }

    public String getQuestion() {
        return question;
    }

    public String getModelAnswer() {
        return modelAnswer;
    }

    public String getAnswer() {
        return answer;
    }
}
